// 新建商品带期初（多仓 P1：建商品时直接填各仓期初）：两个仓各一行 → 提交 → 商品建出、两个仓的账面数就是期初数
const name = "期初测试 " + Date.now();
click(await wait(() => byText(".page-head button", "新建"), 10000));
const d = await wait(() => window.cur_dialog && cur_dialog.display && cur_dialog.fields_dict.product_name && cur_dialog, 10000);
if (!d) return {ok: false, why: "新建商品弹窗没出来"};
const grid = d.fields_dict.opening;
if (!grid) return {ok: false, why: "新建商品弹窗没有期初表", fields: Object.keys(d.fields_dict)};
await d.set_value("product_name", name);
const rows = [{warehouse: "${v.wh1}", qty: 5, unit_cost: 20}, {warehouse: "${v.wh2}", qty: 3, unit_cost: 20}];
grid.df.data = rows.map((row, i) => ({idx: i + 1, name: "row" + i, ...row}));
grid.grid.refresh();
await sleep(500);
click(d.get_primary_btn()[0]);
await sleep(4000);
const product = (await call("frappe.client.get_list", {doctype: "ERP Product", filters: {product_name: name}, fields: ["name"]}, "GET") || [])[0];
if (!product) return {ok: false, why: "商品没建出来", message: msg(), alerts: alerts()};
const stock = async wh => { const r = await call("pearnly_erp_portal.inventory.api.api_stock", {warehouse: wh, include_zero: 1, limit: 500}, "GET");
  const row = (r || []).find(x => x.product === product.name || x.name === product.name); return row ? Number(row.qty_on_hand ?? row.qty ?? 0) : 0; };
const got = [await stock("${v.wh1}"), await stock("${v.wh2}")];
return {ok: got[0] === 5 && got[1] === 3, product: product.name, got, message: msg()};
