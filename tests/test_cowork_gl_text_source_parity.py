def text_fixtures(rng):
	verbs = ("โอนเงิน", "ค่าอาหาร", "ถอนเงินสด", "รับโอน", "จ่ายบิล", "")
	for _ in range(180):
		lines = []
		balance = rng.choice((1000.0, 12345.67, 0.0))
		if rng.random() < 0.6:
			lines.append(f"ยอดยกมา {balance:,.2f}")
		for _ in range(rng.randrange(1, 6)):
			amount = rng.choice((100.0, 50.0, 1250.5, 115586.5, 0.0, -30.0, -300.0))
			balance = round(balance + amount, 2)
			lines.append(f"{rng.choice(('01/06/69','02/06/2569','2026-06-03'))} "
				f"{rng.choice(verbs)} {abs(amount):,.2f} {balance:,.2f}")
		if rng.random() < 0.4:
			lines.append(f"ยอดยกไป {balance:,.2f}")
		yield "lines", "\n".join(lines) + "\n"
	# The realistic column-stacked layout, plus small variations of it.
	yield "columns", KBANK_TEXT
	yield "columns", KBANK_TEXT.replace("รับโอนเงิน", "ฝากด้วยเช็ค")
	yield "columns", "01/06/69\nรายละเอียด\n"
	yield "columns", "no dates here\n"
	yield "columns", ""
	yield "lines", ""
	yield "lines", "หัวข้อรายงาน\nไม่ใช่วันที่ โอนเงิน 100.00 1,100.00\n"


def run(root=None, source_text=None):
	payload = (source_text if source_text is not None
		else {path: (Path(root) / path).read_text() for path in HASHES})
	legacy = load_legacy(payload)

	# The keyword tables and the account-code pattern are compared value by value.
	assert list(legacy["gl"]["_GL_OPENING_KW"]) == list(gl_sheets.GL_OPENING_KEYWORDS)
	assert legacy["common"]["_ACCT_RE"].pattern == gl_sheets.ACCOUNT_CODE_RE.pattern
	for legacy_name, native_name in (("_GL_DATE_H", "GL_DATE_H"), ("_GL_DOC_H", "GL_DOC_H"),
			("_GL_DESC_H", "GL_DESC_H"), ("_GL_DEBIT_H", "GL_DEBIT_H"),
			("_GL_CRED_H", "GL_CREDIT_H"), ("_GL_ACCT_H", "GL_ACCOUNT_H"),
			("_GL_BAL_H", "GL_BALANCE_H")):
		assert set(legacy["common"][legacy_name]) == set(getattr(gl_sheets, native_name)), native_name

	rng = random.Random(20260922)
	counts = {"gl_batches": 0, "gl_rows": 0, "gl_opening": 0, "gl_closing_printed": 0,
		"gl_header_missing": 0, "gl_unreadable": 0, "gl_filtered": 0, "gl_csv": 0}
	for _ in range(220):
		content = gl_workbook(rng)
		filter_code = "5301" if rng.random() < 0.3 else ""
		expected = normalized_gl(legacy["gl"]["parse_gl_excel"](content, "gl.xlsx", filter_code))
		produced = normalized_gl(gl_sheets.parse_gl_workbook(content, "gl.xlsx", filter_code))
		assert expected == produced, (expected, produced)
		counts["gl_batches"] += 1
		if not produced["ok"]:
			counts["gl_header_missing"] += 1 if produced["error_code"] == "gl_headers_not_found" else 0
			counts["gl_unreadable"] += 1 if produced["error_code"] is None else 0
			continue
		counts["gl_rows"] += produced["row_count"]
		counts["gl_opening"] += 1 if produced["opening"] else 0
		counts["gl_closing_printed"] += 1 if produced["closing_printed"] else 0
		counts["gl_filtered"] += 1 if filter_code and produced["row_count"] else 0
	# Fixed shapes: CSV with the right extension, CSV without any extension, an
	# empty file and a file that is only text.
	csv_bytes = ("วันที่,คำอธิบาย,เดบิต,เครดิต\n01/06/2569,ค่าอาหาร,100,\n"
		"02/06/2569,โอนเงิน,,50\n").encode("utf-8")
	for content, filename, filter_code in ((csv_bytes, "gl.csv", ""),
			(csv_bytes, "gl.xlsx", ""), (csv_bytes, "gl.dat", "6201"),
			(b"", "gl.xlsx", ""), (b"not a workbook at all", "gl.xlsx", "")):
		expected = normalized_gl(legacy["gl"]["parse_gl_excel"](content, filename, filter_code))
		produced = normalized_gl(gl_sheets.parse_gl_workbook(content, filename, filter_code))
		assert expected == produced, (filename, expected, produced)
		counts["gl_batches"] += 1
		counts["gl_csv"] += 1 if produced.get("ok") and filename.endswith((".csv", ".xlsx")) else 0
		if not produced["ok"]:
			counts["gl_header_missing"] += 1 if produced["error_code"] == "gl_headers_not_found" else 0
			counts["gl_unreadable"] += 1 if produced["error_code"] is None else 0
		else:
			counts["gl_rows"] += produced["row_count"]

	counts.update({"text_batches": 0, "text_rows": 0, "text_deposits": 0, "text_withdrawals": 0,
		"text_opening": 0, "text_closing": 0, "kbank_batches": 0, "kbank_rows": 0})
	for kind, content in text_fixtures(rng):
		if kind == "lines":
			expected = legacy["text"]["_parse_stmt_text_lines"](content, "kbank")
			produced = bank_text.parse_statement_text_lines(content, "kbank")
		else:
			expected = legacy["text"]["_parse_kbank_text_columns"](content)
			produced = bank_text.parse_kbank_text_columns(content)
		assert text_state(expected[0]) == text_state(produced[0]), (kind, expected[0], produced[0])
		assert (expected[1], expected[2]) == (produced[1], produced[2]), (kind, expected[1:], produced[1:])
		counts["text_batches"] += 1
		counts["kbank_batches"] += 1 if kind == "columns" else 0
		counts["kbank_rows"] += len(produced[0]) if kind == "columns" else 0
		counts["text_rows"] += len(produced[0]) if kind == "lines" else 0
		if kind == "lines":
			counts["text_deposits"] += sum(1 for row in produced[0] if row.deposit > 0)
			counts["text_withdrawals"] += sum(1 for row in produced[0] if row.withdrawal > 0)
			counts["text_opening"] += 1 if produced[1] else 0
			counts["text_closing"] += 1 if produced[2] else 0

	counts.update({"pdf_batches": 0, "pdf_pages": 0, "pdf_empty": 0})
	pdf_fixtures = [
		minimal_pdf("hello pearnly"),
		minimal_pdf("K BANK 01/06/69 100.00 1,100.00"),
		b"not a pdf at all",
		b"",
	]
	for content in pdf_fixtures:
		expected = legacy["pdf"]["_pdf_extract_text_safe"](content)
		produced = table_io.extract_pdf_text_pages(content)
		assert expected == produced, (expected, produced)
		counts["pdf_batches"] += 1
		counts["pdf_pages"] += 1 if produced else 0
		counts["pdf_empty"] += 1 if not produced else 0

	print({"source": SOURCE_SHA, "counts": counts, "differences": 0})
	floors = {"gl_batches": 200, "gl_rows": 100, "gl_opening": 30,
		"gl_closing_printed": 30, "gl_header_missing": 3, "gl_unreadable": 1,
		"gl_csv": 2, "gl_filtered": 5, "text_batches": 180, "text_rows": 250,
		"text_deposits": 150, "text_withdrawals": 40, "text_opening": 50,
		"text_closing": 50, "kbank_batches": 3, "kbank_rows": 3, "pdf_batches": 4,
		"pdf_pages": 2, "pdf_empty": 1}
	for name, floor in floors.items():
		if counts[name] < floor:
			raise SystemExit(f"fixture coverage below the floor: {name}={counts[name]} < {floor}")
	raise SystemExit(0)


def minimal_pdf(text):
	"""A one-page PDF carrying ``text`` in its text layer (built here, not written)."""
	objects = [
		b"<< /Type /Catalog /Pages 2 0 R >>",
		b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
		b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 200 200] "
		b"/Resources << /Font << /F1 5 0 R >> >> /Contents 4 0 R >>",
	]
	stream = ("BT /F1 12 Tf 20 100 Td (%s) Tj ET" % text).encode("latin-1")
	objects.append(b"<< /Length " + str(len(stream)).encode() + b" >>\nstream\n"
		+ stream + b"\nendstream")
	objects.append(b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>")
	out = bytearray(b"%PDF-1.4\n")
	offsets = []
	for number, body in enumerate(objects, 1):
		offsets.append(len(out))
		out += str(number).encode() + b" 0 obj\n" + body + b"\nendobj\n"
	xref = len(out)
	out += b"xref\n0 " + str(len(objects) + 1).encode() + b"\n0000000000 65535 f \n"
	for offset in offsets:
		out += ("%010d 00000 n \n" % offset).encode()
	out += (b"trailer\n<< /Size " + str(len(objects) + 1).encode() + b" /Root 1 0 R >>\n"
		+ b"startxref\n" + str(xref).encode() + b"\n%%EOF\n")
	return bytes(out)


